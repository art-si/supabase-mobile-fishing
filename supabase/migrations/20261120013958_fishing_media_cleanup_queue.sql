-- Applied to the confirmed project as 20261120013958.
-- Only a committed DELETE of a media index authorizes object deletion. No orphan scans,
-- age-based draft deletion, Storage SQL deletion, or changes to upload/publishing behavior.
create table fishing_private.media_deletions (
  id uuid primary key,
  path_hash bytea not null unique check(octet_length(path_hash)=32),
  owner_id uuid,
  path text,
  state text not null default 'pending' check(state in ('pending','working','failed','done')),
  attempts integer not null default 0 check(attempts between 0 and 12),
  created_at timestamptz not null default now(),
  next_attempt_at timestamptz not null default now(),
  lease_token uuid,
  lease_until timestamptz,
  failure_code text check(failure_code in ('PATH_INVALID','INDEX_PRESENT','LEASE_EXPIRED','STORAGE_DELETE_FAILED','STORAGE_PROTOCOL_ERROR')),
  completed_at timestamptz,
  check((lease_token is null) = (lease_until is null)),
  check(state<>'failed' or failure_code is not null),
  check((state='working') = (lease_token is not null and lease_until is not null)),
  check((state='done' and path is null and owner_id is null and completed_at is not null)
     or (state<>'done' and path is not null and owner_id is not null and completed_at is null))
);
create index media_deletions_pending_idx on fishing_private.media_deletions(next_attempt_at,id) where state='pending';
create index media_deletions_working_idx on fishing_private.media_deletions(lease_until,id) where state='working';
alter table fishing_private.media_deletions enable row level security;
revoke all on fishing_private.media_deletions from public,anon,authenticated;
grant usage on schema fishing_private to service_role;
grant select,insert,update on fishing_private.media_deletions to service_role;

create function fishing_private.valid_cleanup_path(owner uuid,asset uuid,object_path text)
returns boolean language sql immutable security invoker set search_path='' as $$
  select object_path in (owner::text||'/'||asset::text||'.jpg',owner::text||'/'||asset::text||'.mp4');
$$;

create function fishing_private.enqueue_deleted_media() returns trigger
language plpgsql security invoker set search_path='' as $$
declare valid boolean:=fishing_private.valid_cleanup_path(old.owner_id,old.id,old.path);
begin
  perform pg_advisory_xact_lock(hashtextextended(old.path,68009));
  insert into fishing_private.media_deletions(id,path_hash,owner_id,path,state,failure_code)
  values(old.id,sha256(convert_to(old.path,'UTF8')),old.owner_id,old.path,
    case when valid then 'pending' else 'failed' end,case when valid then null else 'PATH_INVALID' end)
  on conflict(path_hash) do nothing;
  return old;
end;
$$;
create trigger enqueue_deleted_media after delete on public.media_assets
for each row execute function fishing_private.enqueue_deleted_media();

-- Paths generated by the upload service are never reusable. Completed jobs retain only
-- an opaque digest/id and timing, so a late worker cannot delete a replacement object.
create function fishing_private.guard_retired_media_path() returns trigger
language plpgsql security invoker set search_path='' as $$
begin
  perform pg_advisory_xact_lock(hashtextextended(new.path,68009));
  if fishing_private.valid_cleanup_path(new.owner_id,new.id,new.path) and exists(
    select 1 from fishing_private.media_deletions where path_hash=sha256(convert_to(new.path,'UTF8'))
  ) then raise exception 'MEDIA_PATH_RETIRED'; end if;
  return new;
end;
$$;
create trigger guard_retired_media_path before insert or update of path on public.media_assets
for each row execute function fishing_private.guard_retired_media_path();

create function public.fishing_media_cleanup_claim(batch_limit integer default 20)
returns table(job_id uuid,owner_id uuid,path text,lease_token uuid,attempt integer)
language plpgsql security invoker set search_path='' as $$
declare job fishing_private.media_deletions; lease uuid;
begin
  if batch_limit is null or batch_limit<1 or batch_limit>20 then raise exception 'INVALID_BATCH'; end if;
  update fishing_private.media_deletions q set state='failed',lease_token=null,lease_until=null,failure_code='LEASE_EXPIRED'
    where q.state='working' and q.lease_until<=clock_timestamp() and q.attempts>=12;
  for job in select q.* from fishing_private.media_deletions q
    where (q.state='pending' and q.next_attempt_at<=clock_timestamp() and q.attempts<12)
       or (q.state='working' and q.lease_until<=clock_timestamp() and q.attempts<12)
    order by q.next_attempt_at,q.id limit batch_limit for update skip locked
  loop
    if exists(select 1 from public.media_assets m where m.path=job.path) then
      update fishing_private.media_deletions q set state='failed',failure_code='INDEX_PRESENT',lease_token=null,lease_until=null where q.id=job.id;
    else
      lease:=gen_random_uuid();
      update fishing_private.media_deletions q set state='working',attempts=q.attempts+1,
        lease_token=lease,lease_until=clock_timestamp()+interval '5 minutes',failure_code=null where q.id=job.id;
      return query select job.id,job.owner_id,job.path,lease,job.attempts+1;
    end if;
  end loop;
end;
$$;

create function public.fishing_media_cleanup_finish(job_id uuid,lease uuid,succeeded boolean,failure text default 'STORAGE_DELETE_FAILED')
returns text language plpgsql security invoker set search_path='' as $$
declare job fishing_private.media_deletions;
begin
  if succeeded is null or failure is null or failure not in ('STORAGE_DELETE_FAILED','STORAGE_PROTOCOL_ERROR') then raise exception 'INVALID_RESULT'; end if;
  select * into job from fishing_private.media_deletions q
    where q.id=job_id and q.state='working' and q.lease_token=lease and q.lease_until>clock_timestamp() for update;
  if not found then return 'stale'; end if;
  if exists(select 1 from public.media_assets m where m.path=job.path) then
    update fishing_private.media_deletions set state='failed',failure_code='INDEX_PRESENT',lease_token=null,lease_until=null where id=job_id;
  elsif succeeded then
    update fishing_private.media_deletions set state='done',completed_at=clock_timestamp(),path=null,owner_id=null,
      lease_token=null,lease_until=null,failure_code=null where id=job_id;
  else
    update fishing_private.media_deletions set state=case when attempts>=12 then 'failed' else 'pending' end,
      failure_code=failure,lease_token=null,lease_until=null,
      next_attempt_at=clock_timestamp()+make_interval(secs=>least(3600,30*power(2,job.attempts-1))::integer)
      where id=job_id;
  end if;
  return (select state from fishing_private.media_deletions where id=job_id);
end;
$$;

revoke all on function fishing_private.valid_cleanup_path(uuid,uuid,text),fishing_private.enqueue_deleted_media(),
  fishing_private.guard_retired_media_path(),public.fishing_media_cleanup_claim(integer),
  public.fishing_media_cleanup_finish(uuid,uuid,boolean,text) from public,anon,authenticated;
grant execute on function fishing_private.valid_cleanup_path(uuid,uuid,text),fishing_private.enqueue_deleted_media(),
  fishing_private.guard_retired_media_path(),public.fishing_media_cleanup_claim(integer),
  public.fishing_media_cleanup_finish(uuid,uuid,boolean,text) to service_role;
